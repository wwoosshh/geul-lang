#!/usr/bin/env python3
"""3단계 성능 — 선형·어텐션 커널들의 글 소스(커널.gl)를 만든다. 누적 변수가 수십 개라 손으로 쓰면 틀리기 쉬워서 만든다.

  python research/gpu/3단계/커널생성.py            (커널.gl · 커널반.gl · 커널프롬.gl)
  python research/gpu/3단계/커널생성.py -o 파일.gl   (짧은실수 KV 판 하나만 — 대조용)

커널반.gl (4단계 2 — 밝힌 정밀도): KV 캐시를 반실수로 둔 판. c_attn 의 끝손질이 키·값을 `으로 반실수` 로 좁혀 쓰고(반올림 한 번 —
소스가 밝힌 것), 어텐션은 읽어서 넓혀(정확) 짧은실수로 계산한다. 키의 배치는 [머리][조각][d][위치 64] — 조각 하나(8 KB)가 붙어 있어
생성의 어텐션이 띄엄띄엄 읽지 않는다(값과는 상관없다). 그 밖의 커널과 순서 약속은 커널.gl 과 같다.

순서의 약속 (모든 판이 지킨다 — 그래서 어느 판으로, 몇 행을 함께 계산해도 칸마다 비트가 같다):
  p_g      = Σ 입력[r, k] · 가중치[k, n]   (k ≡ g mod 4, k 오름차순, 곱해더하기로 차례로 — 반올림 한 번씩)   g = 0 … 3
  출력[r, n] = 끝손질( ((p₀ + p₂) + (p₁ + p₃)) + 치우침[n] )
가닥 넷은 cuBLAS 와 같은 큰 타일(스레드 하나가 8 × 8 칸)을 허락하면서, 토큰 하나를 계산할 때(행 하나)도 열마다 사슬이 넷이라 메모리를
충분히 동시에 읽을 수 있게 고른 수다. 판:
  타일선형·타일선형넷 — 블록 하나(256 스레드 = 가닥 4 × 64)가 64 × 64 칸. k 를 32 줄씩 공유 메모리 세 판에 앞서 올린다
                     (넷 = 가중치를 16 바이트 비동기복사로 — 열수가 64 의 배수일 때 — 그리고 입력은 16 바이트 읽기로 레지스터를 거쳐 한
                     조각 앞서 판에 뒤집어 둔다(레지): 4 바이트 비동기복사 2048 번으로 옮기던 판은 옮기기만으로 cuBLAS 전체 시간이 들었다).
  작은타일선형         — 32 × 32 칸(블록이 적게 나오는 모양). 입력은 같은 레지스터 길로.
  줄선형R             — 행 R 개(1 또는 4)를 블록 하나(128 스레드 = 가닥 4 × 열 32)가 열 32 개씩. 깊은줄선형1 은 가중치를 48 개씩 먼저 읽는다.
  생성메가             — 토큰 생성(배치 1) 전체를 커널 하나로(아래).
끝손질: 그대로 / _잔차(잔차 + 값) / _겔루(tanh 근사 GELU) / _KV(열 0..767 은 q 로 출력에, 768.. 은 키칸, 1536.. 은 값칸의 캐시 자리에).
KV 캐시(층마다): 키는 [문장][머리][d][위치](전치 — 생성의 점수가 위치 순으로 붙여 읽는다), 값은 [문장][머리][위치][d].

어텐션의 순서 약속 (질의 하나 — 위치 p, 머리 h). 키를 위치 64 개씩의 조각 σ = 0 … ⌊p/64⌋ 로 나눈다(조각 σ 의 키
t = 64σ … min(64σ + 63, p)):
  s_t  = (Σ_d q_d · k_td, d 오름차순 곱해더하기) × 0.125
  m_σ  = max_{t∈σ} s_t (어느 순서로 구해도 같다),   e_t = 근사지수(s_t − m_σ)
  l_σ  = Σ_{t∈σ} e_t (t 오름차순, 0 에서부터 더하기),   o_σd = Σ_{t∈σ} e_t · v_td (t 오름차순 곱해더하기)
  접기 — (M, L, O) = (m₀, l₀, o₀), 그다음 σ = 1, 2, … 차례로: M' = max(M, m_σ), 가 = 근사지수(M − M'), 나 = 근사지수(m_σ − M'),
         L = 곱해더하기(l_σ, 나, L·가), O_d = 곱해더하기(o_σd, 나, O_d·가), M = M'
  출력_d = O_d / L
조각 안은 짧은 사슬이고 조각들은 위치 순서대로 접히므로, 프롬프트 처리는 점수를 한 번만 계산하고(점수 표를 두지 않는다) 생성은 조각을
여러 블록이 나눠 맡을 수 있다. 판: 흐름어텐션(프롬프트 — 블록 하나가 질의 64 개, 조각마다 한 번에), 조각어텐션 + 조각접기(생성 —
조각을 블록들이 나눠 맡고 차례로 접는다), 메가커널 안의 어텐션(같은 계산 — 머리마다 마지막에 도착한 블록이 접는다).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
끝손질들 = ("", "_잔차", "_겔루", "_KV")
# KV 캐시의 원소 타입: "짧은실수"(커널.gl) 또는 "반실수"(커널반.gl). source(KV) 가 정한다.
KV = "짧은실수"


def 좁힘(v):
    """KV 캐시에 쓰는 값 — 반실수 판이면 밝혀서 좁힌다(가까운 쪽 반올림, 넘치면 오류 칸에 4)."""
    return v if KV == "짧은실수" else f"({v}) 으로 반실수"


def 키자리(바탕, 열d, 위치):
    """키 칸의 자리 — 열d = 머리·64 + d (식), 위치 = 그 행의 위치(식). 짧은실수 판: [머리][d][위치](전치),
    반실수 판: [머리][조각][d][위치 64] (조각 = 위치 / 64)."""
    if KV == "짧은실수":
        return f"{바탕} + ({열d}) * 최대길이 + {위치}"
    # 열d · 위치는 음이 아니다 — / 64 · % 64 를 >> 6 · & 63 으로(같은 값; 나눗셈은 64 비트 정수면 GPU 에서 비싸다)
    return f"{바탕} + (({열d}) >> 6) * 64 * 최대길이 + ({위치} >> 6) * 4096 + (({열d}) & 63) * 64 + ({위치} & 63)"


def 머리(epi, 미리=False):
    p = "짧은실수 참조 입력에서 짧은실수 참조 가중치와 짧은실수 참조 치우침과 "
    if epi == "_잔차":
        p += "짧은실수 참조 잔차와 "
    if epi == "_KV":
        p += f"{KV} 참조 키칸과 {KV} 참조 값칸과 "
    p += "짧은실수 참조 출력에 정수 행수로 정수 깊이로 정수 열수로"
    if epi == "_KV":
        p += " 정수 묶음안행수로 정수 위치시작으로 정수 최대길이로"
    if 미리:
        p += " 짧은실수 참조 다음을 정수 다음수로"
    return p


def 끝(epi, v, 행, 열, 자리, ind):
    """값 v(치우침까지 더한 것)를 행·열에 쓰는 끝손질. 자리 = KV 캐시의 행 바탕(행마다 한 번 구해 둔 것)."""
    if epi == "":
        return [f"{ind}출력[{행} * 열수 + {열}] = {v}."]
    if epi == "_잔차":
        return [f"{ind}출력[{행} * 열수 + {열}] = 잔차[{행} * 열수 + {열}] + {v}."]
    if epi == "_겔루":
        return [f"{ind}u = 0.7978845608 * ({v} + 0.044715 * {v} * {v} * {v}).",
                f"{ind}th = 1.0 - 2.0 / (근사지수(2.0 * u) + 1.0).",
                f"{ind}출력[{행} * 열수 + {열}] = 0.5 * {v} * (1.0 + th)."]
    return [f"{ind}{열} < 768이면 {{ 출력[{행} * 768 + {열}] = {v}. }}",
            f"{ind}아니면 {열} < 1536이면 {{ 키칸[{키자리(자리, f'{열} - 768', '자리위')}] = {좁힘(v)}. }}",
            f"{ind}아니면 {{ 값칸[{자리} + (({열} - 1536) / 64) * 최대길이 * 64 + 자리위 * 64 + ({열} - 1536) % 64] = {좁힘(v)}. }}"]


def 자리두기(행, ind):
    """행의 KV 캐시 자리: 자리 = 문장 · 768 · 최대길이, 자리위 = 위치시작 + 행 % 묶음안행수. 문장이 하나면 나눗셈을 건너뛴다(값은 같다)."""
    return [f"{ind}묶음안행수 >= 행수이면 {{ 자리 = 0. 자리위 = 위치시작 + {행}. }}",
            f"{ind}아니면 {{ 자리 = ({행} / 묶음안행수) * 768 * 최대길이. 자리위 = 위치시작 + {행} % 묶음안행수. }}"]


def 타일선형(epi, 넷=False, 이름=None, 레지=False):
    """64 × 64 칸을 블록 하나(256 스레드 = 가닥 4 × 64)가. k 를 32 줄씩, 공유 메모리 세 판에 비동기복사로 두 조각 앞서 올린다.
    스레드 하나가 8 × 8 칸 — 행 {ty·4 + r, 32 + ty·4 + r}, 열 {tx·4 + c, 32 + tx·4 + c} (r, c < 4). 이렇게 두면 스레드가 읽는
    입력·가중치 조각이 네 칸씩 붙어 있어서 컴파일러가 네 칸 묶어 읽기(ld.shared.v4)로 낸다.
    판: 입력 [판 3][k 32][행 64] — 자리 (k, m) 는 m ^ s(k), s(k) = 8·((k/8) % 4) (옮겨 쓸 때 뱅크가 겹치지 않게 비튼다),
        가중치 [판 3][k 32][열 64].
    넷 = 참: 가중치를 16 바이트씩 옮긴다 — 열수가 64 의 배수이고 가중치의 시작이 16 바이트 정렬일 때만(호스트가 확인한다).
    레지 = 참: 입력 조각을 스레드마다 16 바이트 읽기 둘로 레지스터에 받아 다음 조각을 계산하는 동안 들고 있다가 판에 뒤집어 쓴다
    (깊이가 4 의 배수라는 약속 — 깊이4 = 깊이 / 4 · 4 로 컴파일러에 알린다)."""
    I8, J8 = range(8), range(8)
    BK, AB, BB = 32, 32 * 64, 32 * 64
    B0 = 3 * AB
    판 = "공유판48"
    이름 = 이름 or f"타일선형{'넷' if 넷 else ''}{epi}"
    행식 = lambda i: f"ty * 4 + {i}" if i < 4 else f"32 + ty * 4 + {i - 4}"
    열식 = lambda j: f"tx * 4 + {j}" if j < 4 else f"32 + tx * 4 + {j - 4}"

    def 올리기(판번호, ind):
        """a원·b원 이 가리키는 조각을 판 번호(식)에 비동기로 올린다."""
        out = [f"{ind}올판 = {판번호}."]
        if not 레지:
            out += [f"{ind}비동기복사(판 에, 올판 * {AB} + a저장 + {64 * e} 를, 입력 에서, a원 + {e} 로)." for e in range(8)]
        if 넷:
            out += [f"{ind}비동기복사16(판 에, {B0} + 올판 * {BB} + b저장 를, 가중치 에서, b원 로).",
                    f"{ind}비동기복사16(판 에, {B0} + 올판 * {BB} + b저장 + 1024 를, 가중치 에서, b원 + 열16 로)."]
        else:
            out += [f"{ind}비동기복사(판 에, {B0} + 올판 * {BB} + b저장 + {(e // 2) * 64 + 32 * (e % 2)} 를, 가중치 에서, "
                    f"b원{e % 2} + 열줄{e // 2} 로)." for e in range(8)]
        return out

    def 다음(ind):
        out = [] if 레지 else [f"{ind}a원 = a원 + {BK}."]
        out += [f"{ind}b원 = b원 + 열32."] if 넷 else [f"{ind}b원0 = b원0 + 열32.", f"{ind}b원1 = b원1 + 열32."]
        return out

    def 읽기A(ind):
        """입력 조각(행 64 × k 32)을 레지스터로 — 스레드마다 두 행(ar0, ar0 + 32)의 네 칸씩, 16 바이트 읽기 둘."""
        return [f"{ind}ra{h}_{u} = 입력[ra원{h} + {u}]." for h in range(2) for u in range(4)]

    def 쓰기A(판식, ind):
        """레지스터의 입력 조각을 판의 [k][행 ^ s(k)] 자리에 (가닥마다 네 행씩 붙여 읽을 수 있게 뒤집어 둔다)."""
        return [f"{ind}판[{판식} + 저a + {u * 64 + 32 * h}] = ra{h}_{u}." for h in range(2) for u in range(4)]

    L = [f"(* 64 × 64 칸을 블록 하나가 — 가닥 g 의 스레드 64 개가 k ≡ g (mod 4) 를 맡고, 스레드 하나가 8 × 8 칸. 커널생성.py 의 설명 *)",
         f"(* 실행한도 {이름} 256 2 *)",
         f"[{머리(epi)} {이름}]는 {{",
         "    정수 tid = 블록안가로().",
         "    정수 가닥 = tid / 64.",
         "    정수 t64 = tid % 64.",
         "    정수 ty = t64 / 8.",
         "    정수 tx = t64 % 8.",
         "    정수 행0 = 블록가로() * 64.",
         "    정수 열0 = 블록세로() * 64.",
         f"    짧은실수 참조 판 = {판}().",
         "    정수 a행 = 행0 + tid / 4.",
         "    a행 >= 행수이면 { a행 = 행수 - 1. }",
         "    정수 ak = (tid % 4) * 8.",
         "    정수 a저장 = ak * 64 + ((tid / 4) ^ ((tid % 4) * 8)).",
         "    정수 a원 = a행 * 깊이 + ak.",
         "    정수 열32 = 열수 * 32."]
    if 넷:
        L += ["    정수 열16 = 열수 * 16.",
              "    정수 b저장 = (tid / 16) * 64 + (tid % 16) * 4.",
              "    정수 b원 = (tid / 16) * 열수 + 열0 + (tid % 16) * 4."]
    else:
        L += ["    정수 wp = tid / 32.", "    정수 ln = tid % 32.", "    정수 b저장 = 4 * wp * 64 + ln."]
        for e in range(2):
            L += [f"    정수 c{e} = 열0 + ln + {32 * e}.", f"    c{e} >= 열수이면 {{ c{e} = 열수 - 1. }}",
                  f"    정수 b원{e} = 4 * wp * 열수 + c{e}."]
        L += [f"    정수 열줄{r} = {r} * 열수." for r in range(4)]
    L.append(f"    정수 타일수 = 깊이 / {BK}.")
    L.append("    정수 올판 = 0.")
    if 레지:
        L += ["    정수 ar0 = tid / 8.",
              "    정수 ac = (tid % 8) * 4.",
              "    정수 sa = 8 * ((tid % 8) / 2).",
              "    정수 깊이4 = 깊이 / 4 * 4.",
              "    정수 행a0 = 행0 + ar0.", "    행a0 >= 행수이면 { 행a0 = 행수 - 1. }",
              "    정수 행a1 = 행0 + ar0 + 32.", "    행a1 >= 행수이면 { 행a1 = 행수 - 1. }",
              "    정수 ra원0 = 행a0 * 깊이4 + ac.",
              "    정수 ra원1 = 행a1 * 깊이4 + ac.",
              "    정수 저a = ac * 64 + (ar0 ^ sa)."]
        L += [f"    짧은실수 ra{h}_{u} = 입력[ra원{h} + {u}]." for h in range(2) for u in range(4)]
        L += 쓰기A("0", "    ")
    L += 올리기("0", "    ")
    L.append("    비동기묶기().")
    L.append("    타일수 > 1이면 {")
    L += 다음("        ")
    L += 올리기("1", "        ")
    if 레지:
        L += [f"        ra원{h} = ra원{h} + {BK}." for h in range(2)]
        L += 읽기A("        ")
    L.append("    }")
    L.append("    비동기묶기().")
    L.append("    짧은실수 영 = 0 으로 짧은실수.")
    L += [f"    짧은실수 a{i}_{j} = 영." for i in I8 for j in J8]
    L += [f"    짧은실수 x{i} = 영." for i in I8]
    L += [f"    짧은실수 w{j} = 영." for j in J8]
    L.append("    정수 aq = 0.")
    L.append("    정수 버퍼 = 0.")
    L.append("    정수 앞판 = 2.")
    L.append("    반복 (정수 t는 0부터 타일수 전까지) {")
    L.append("        비동기기다리기(1).")
    L.append("        동기화().")
    L.append("        t + 2 < 타일수이면 {")
    L += 다음("            ")
    L += 올리기("앞판", "            ")
    L.append("        }")
    L.append("        비동기묶기().")
    L.append(f"        정수 B바탕 = {B0} + 버퍼 * {BB} + 가닥 * 64 + tx * 4.")
    for q in range(BK // 4):
        if q % 2 == 0:
            L.append(f"        aq = 버퍼 * {AB} + 가닥 * 64 + ((ty * 4) ^ {8 * (q // 2)}).")
        L += [f"        x{r} = 판[aq + {q * 256 + r}]." for r in range(4)]
        L += [f"        x{4 + r} = 판[aq + {q * 256 + 32 + r}]." for r in range(4)]
        L += [f"        w{c} = 판[B바탕 + {q * 256 + c}]." for c in range(4)]
        L += [f"        w{4 + c} = 판[B바탕 + {q * 256 + 32 + c}]." for c in range(4)]
