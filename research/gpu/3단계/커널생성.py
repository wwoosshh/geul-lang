def 몸(줄들, 바꿈, 앞줄=()):
    """커널 하나의 글 소스(머리 주석·실행한도·서명 줄 뒤부터 끝 '}' 앞까지)를 메가커널 안의 블록으로 — 배열·좌표의 이름을 바꿔 낀다.
    산술은 같은 생성기에서 나오므로 따로 도는 커널과 비트가 같다. 바꿈: [(정규식, 바꿀 글)] — 앞에서부터 차례로."""
    import re
    본문 = 줄들[3:-1]
    out = list(앞줄)
    for 줄 in 본문:
        for 꼴, 새 in 바꿈:
            줄 = re.sub(꼴, 새, 줄)
        out.append(줄)
    return out


def 배열바꿈(이름, 새이름, 바탕=None):
    """이름[ … ] 과 '이름 에서, ' 를 새이름(+ 바탕)으로 — 앞뒤가 이름의 일부가 아닐 때만."""
    앞 = r"(?<![\w])"
    if 바탕 is None:
        return [(앞 + 이름 + r"\[", 새이름 + "["), (앞 + 이름 + " 에서, ", 새이름 + " 에서, ")]
    return [(앞 + 이름 + r"\[", 새이름 + "[" + 바탕 + " + "), (앞 + 이름 + " 에서, ", 새이름 + " 에서, " + 바탕 + " + ")]


