#!/usr/bin/env python3
"""3단계 성능 — 선형·어텐션 커널들의 글 소스(커널.gl)를 만든다. 누적 변수가 수십 개라 손으로 쓰면 틀리기 쉬워서 만든다.

  python research/gpu/3단계/커널생성.py [-o research/gpu/3단계/커널.gl]

순서의 약속 (모든 판이 지킨다 — 그래서 어느 판으로, 몇 행을 함께 계산해도 칸마다 비트가 같다):
  p_g      = Σ 입력[r, k] · 가중치[k, n]   (k ≡ g mod 4, k 오름차순, 곱해더하기로 차례로 — 반올림 한 번씩)   g = 0 … 3
  출력[r, n] = 끝손질( ((p₀ + p₂) + (p₁ + p₃)) + 치우침[n] )
가닥 넷은 cuBLAS 와 같은 큰 타일(스레드 하나가 8 × 8 칸)을 허락하면서, 토큰 하나를 계산할 때(행 하나)도 열마다 사슬이 넷이라 메모리를
충분히 동시에 읽을 수 있게 고른 수다. 판은 둘:
  타일선형 — 블록 하나(256 스레드 = 가닥 4 × 64)가 64 × 64 칸. 가중치·입력 조각(k 16 줄)을 공유 메모리에 두 판으로 번갈아 올린다.
  줄선형R  — 행 R 개(1 또는 4)를 블록 하나(128 스레드 = 가닥 4 × 열 32)가 열 32 개씩. 가중치를 16 개씩 먼저 읽고 차례로 곱해더한다.
끝손질: 그대로 / _잔차(잔차 + 값) / _겔루(tanh 근사 GELU) / _KV(열 0..767 은 q 로 출력에, 768.. 은 키칸, 1536.. 은 값칸의 캐시 자리에).

어텐션의 순서 약속 (질의 하나 — 위치 p, 머리 h):
  s_t = (Σ_d q_d · k_td, d 오름차순 곱해더하기) × 0.125            t = 0 … p
  m   = max_t s_t (어느 순서로 구해도 같다)
  e_t = 근사지수(s_t − m)
  l_j = Σ e_t,  o_jd = Σ e_t · v_td   (t ≡ j mod 4, t 오름차순 — 덧셈·곱해더하기로 차례로)   j = 0 … 3
  출력_d = ((o₀d + o₂d) + (o₁d + o₃d)) / ((l₀ + l₂) + (l₁ + l₃))
판은 둘: 줄어텐션(블록 하나가 질의 하나), 타일어텐션(블록 하나가 질의 16 개 — 키·값 조각 64 개씩을 공유 메모리에 함께 올린다;
점수를 두 번 계산한다: 한 번은 최댓값, 한 번은 지수와 합. 같은 계산이라 비트가 같다).
"""
import os
import sys

