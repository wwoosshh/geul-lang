def 머리(epi, 미리=False):
    p = "짧은실수 참조 입력에서 짧은실수 참조 가중치와 짧은실수 참조 치우침과 "
    if epi == "_잔차":
        p += "짧은실수 참조 잔차와 "
    if epi == "_KV":
        p += "짧은실수 참조 키칸과 짧은실수 참조 값칸과 "
    p += "짧은실수 참조 출력에 정수 행수로 정수 깊이로 정수 열수로"
    if epi == "_KV":
        p += " 정수 묶음안행수로 정수 위치시작으로 정수 최대길이로"
    if 미리:
        p += " 짧은실수 참조 다음을 정수 다음수로"
    return p


def 끝(epi, v, 행, 열, 자리, ind):
    """값 v(치우침까지 더한 것)를 행·열에 쓰는 끝손질. 자리 = KV 캐시의 행 바탕(행마다 한 번 구해 둔 것)."""
    if epi == "":
        return [f"{ind}출력[{행} * 열수 + {열}] = {v}."]
    if epi == "_잔차":
        return [f"{ind}출력[{행} * 열수 + {열}] = 잔차[{행} * 열수 + {열}] + {v}."]
    if epi == "_겔루":
        return [f"{ind}u = 0.7978845608 * ({v} + 0.044715 * {v} * {v} * {v}).",
                f"{ind}th = 1.0 - 2.0 / (근사지수(2.0 * u) + 1.0).",
                f"{ind}출력[{행} * 열수 + {열}] = 0.5 * {v} * (1.0 + th)."]
    return [f"{ind}{열} < 768이면 {{ 출력[{행} * 768 + {열}] = {v}. }}",
            f"{ind}아니면 {열} < 1536이면 {{ 키칸[{자리} + {열} - 768] = {v}. }}",
            f"{ind}아니면 {{ 값칸[{자리} + {열} - 1536] = {v}. }}"]


def 자리식(행):
    return f"(({행} / 묶음안행수) * 최대길이 + 위치시작 + {행} % 묶음안행수) * 768"


def 타일선형(epi, 넷=False, 이름=None):
    """64 × 64 칸을 블록 하나(256 스레드 = 가닥 4 × 64)가. k 를 32 줄씩, 공유 메모리 세 판에 비동기복사로 두 조각 앞서 올린다.
    스레드 하나가 8 × 8 칸 — 행 {ty·4 + r, 32 + ty·4 + r}, 열 {tx·4 + c, 32 + tx·4 + c} (r, c < 4). 이렇게 두면 스레드가 읽는
    입력·가중치 조각이 네 칸씩 붙어 있어서 컴파일러가 네 칸 묶어 읽기(ld.shared.v4)로 낸다.
    판: 입력 [판 3][k 32][행 64] — 자리 (k, m) 는 m ^ s(k), s(k) = 8·((k/8) % 4) (옮겨 쓸 때 뱅크가 겹치지 않게 비튼다),
        가중치 [판 3][k 32][열 64].
    넷 = 참: 가중치를 16 바이트씩 옮긴다 — 열수가 64 의 배수이고 가중치의 시작이 16 바이트 정렬일 때만(호스트가 확인한다)."""
    I8, J8 = range(8), range(8)
    BK, AB, BB = 32, 32 * 64, 32 * 64
    B0 = 3 * AB
    판 = "공유판48"
    이름 = 이름 or f"타일선형{'넷' if 넷 else ''}{epi}"
    행식 = lambda i: f"ty * 4 + {i}" if i < 4 else f"32 + ty * 4 + {i - 4}"
    열식 = lambda j: f"tx * 4 + {j}" if j < 4 else f"32 + tx * 4 + {j - 4}"

    def 올리기(판번호, ind):
        """a원·b원 이 가리키는 조각을 판 번호(식)에 비동기로 올린다."""
        out = [f"{ind}올판 = {판번호}."]
        out += [f"{ind}비동기복사(판 에, 올판 * {AB} + a저장 + {64 * e} 를, 입력 에서, a원 + {e} 로)." for e in range(8)]
        if 넷:
            out += [f"{ind}비동기복사16(판 에, {B0} + 올판 * {BB} + b저장 를, 가중치 에서, b원 로).",
                    f"{ind}비동기복사16(판 에, {B0} + 올판 * {BB} + b저장 + 1024 를, 가중치 에서, b원 + 열16 로)."]
        else:
            out += [f"{ind}비동기복사(판 에, {B0} + 올판 * {BB} + b저장 + {(e // 2) * 64 + 32 * (e % 2)} 를, 가중치 에서, "
                    f"b원{e % 2} + 열줄{e // 2} 로)." for e in range(8)]
        return out

    def 다음(ind):
        out = [f"{ind}a원 = a원 + {BK}."]
        out += [f"{ind}b원 = b원 + 열32."] if 넷 else [f"{ind}b원0 = b원0 + 열32.", f"{ind}b원1 = b원1 + 열32."]
        return out

    L = [f"(* 64 × 64 칸을 블록 하나가 — 가닥 g 의 스레드 64 개가 k ≡ g (mod 4) 를 맡고, 스레드 하나가 8 × 8 칸. 커널생성.py 의 설명 *)",
         f"(* 실행한도 {이름} 256 2 *)",
         f"[{머리(epi)} {이름}]는 {{",
         "    정수 tid = 블록안가로().",
         "    정수 가닥 = tid / 64.",
         "    정수 t64 = tid % 64.",
         "    정수 ty = t64 / 8.",
         "    정수 tx = t64 % 8.",
         "    정수 행0 = 블록가로() * 64.",
         "    정수 열0 = 블록세로() * 64.",
         f"    짧은실수 참조 판 = {판}().",
         "    정수 a행 = 행0 + tid / 4.",
         "    a행 >= 행수이면 { a행 = 행수 - 1. }",
         "    정수 ak = (tid % 4) * 8.",
         "    정수 a저장 = ak * 64 + ((tid / 4) ^ ((tid % 4) * 8)).",
         "    정수 a원 = a행 * 깊이 + ak.",
         "    정수 열32 = 열수 * 32."]
    if 넷:
        L += ["    정수 열16 = 열수 * 16.",
              "    정수 b저장 = (tid / 16) * 64 + (tid % 16) * 4.",
              "    정수 b원 = (tid / 16) * 열수 + 열0 + (tid % 16) * 4."]
    else:
        L += ["    정수 wp = tid / 32.", "    정수 ln = tid % 32.", "    정수 b저장 = 4 * wp * 64 + ln."]
        for e in range(2):
            L += [f"    정수 c{e} = 열0 + ln + {32 * e}.", f"    c{e} >= 열수이면 {{ c{e} = 열수 - 1. }}",
                  f"    정수 b원{e} = 4 * wp * 열수 + c{e}."]
        L += [f"    정수 열줄{r} = {r} * 열수." for r in range(4)]
    L.append(f"    정수 타일수 = 깊이 / {BK}.")
    L.append("    정수 올판 = 0.")
    L += 올리기("0", "    ")
    L.append("    비동기묶기().")
    L.append("    타일수 > 1이면 {")
    L += 다음("        ")
    L += 올리기("1", "        ")
    L.append("    }")
    L.append("    비동기묶기().")
    L.append("    짧은실수 영 = 0 으로 짧은실수.")
    L += [f"    짧은실수 a{i}_{j} = 영." for i in I8 for j in J8]
    L += [f"    짧은실수 x{i} = 영." for i in I8]
    L += [f"    짧은실수 w{j} = 영." for j in J8]
    L += [f"    정수 ty4x{s} = (ty * 4) ^ {8 * s}." for s in range(4)]
    L.append("    정수 aq = 0.")
    L.append("    정수 버퍼 = 0.")
    L.append("    정수 앞판 = 2.")
    L.append("    반복 (정수 t는 0부터 타일수 전까지) {")
    L.append("        비동기기다리기(1).")
    L.append("        동기화().")
    L.append("        t + 2 < 타일수이면 {")
    L += 다음("            ")
    L += 올리기("앞판", "            ")
    L.append("        }")
    L.append("        비동기묶기().")
    L.append(f"        정수 B바탕 = {B0} + 버퍼 * {BB} + 가닥 * 64 + tx * 4.")
    for q in range(BK // 4):
        if q % 2 == 0:
            L.append(f"        aq = 버퍼 * {AB} + 가닥 * 64 + ty4x{q // 2}.")
        L += [f"        x{r} = 판[aq + {q * 256 + r}]." for r in range(4)]
        L += [f"        x{4 + r} = 판[aq + {q * 256 + 32 + r}]." for r in range(4)]
        L += [f"        w{c} = 판[B바탕 + {q * 256 + c}]." for c in range(4)]
        L += [f"        w{4 + c} = 판[B바탕 + {q * 256 + 32 + c}]." for c in range(4)]
        L += [f"        a{i}_{j} = 곱해더하기(x{i}, w{j}, a{i}_{j})." for i in I8 for j in J8]
    L.append("        버퍼 = 버퍼 + 1.")
    L.append("        버퍼 == 3이면 { 버퍼 = 0. }")
    L.append("        앞판 = 앞판 + 1.")
    L.append("        앞판 == 3이면 { 앞판 = 0. }")
    L.append("    }")
    L.append("    동기화().")
    L.append("    (* 가닥 합치기: 가닥 2·3 이 내놓고 0·1 이 더한다(q₀ = p₀ + p₂, q₁ = p₁ + p₃). 그다음 0·1 이 q 를 판에 두고,")
    L.append("       네 가닥이 칸을 나눠 (q₀ + q₁) + 치우침 과 끝손질을 한다 *)")
    for h in (0, 1):
        rows = range(4 * h, 4 * h + 4)
        L.append("    가닥 >= 2이면 {")
        L += [f"        판[{((i - 4 * h) * 8 + j) * 128} + (가닥 - 2) * 64 + t64] = a{i}_{j}." for i in rows for j in J8]
        L.append("    }")
        L.append("    동기화().")
        L.append("    가닥 < 2이면 {")
        L += [f"        a{i}_{j} = a{i}_{j} + 판[{((i - 4 * h) * 8 + j) * 128} + 가닥 * 64 + t64]." for i in rows for j in J8]
        L.append("    }")
        L.append("    동기화().")
    # q₀(가닥 0)과 q₁(가닥 1)을 [가닥][행 64][열 64 + 4] 에 둔다
    L.append("    가닥 < 2이면 {")
    for i in I8:
        for j in J8:
            L.append(f"        판[가닥 * 4352 + ({행식(i)}) * 68 + {열식(j)}] = a{i}_{j}.")
    L.append("    }")
    L.append("    동기화().")
    L += ["    정수 행 = 0.", "    정수 열 = 0.", "    정수 자리 = 0.", "    정수 칸 = 0.", "    짧은실수 v = 영.",
          "    짧은실수 u = 영.", "    짧은실수 th = 영."]
    L.append("    반복 (정수 m는 0부터 16 전까지) {")
    L.append("        칸 = m * 256 + tid.")
    L.append("        행 = 행0 + 칸 / 64.")
    L.append("        열 = 열0 + 칸 % 64.")
    L.append("        (행 < 행수 그리고 열 < 열수)이면 {")
    L.append("            v = (판[(칸 / 64) * 68 + 칸 % 64] + 판[4352 + (칸 / 64) * 68 + 칸 % 64]) + 치우침[열].")
    if epi == "_KV":
        L.append(f"            자리 = {자리식('행')}.")
    L += 끝(epi, "v", "행", "열", "자리", "            ")
    L.append("        }")
    L.append("    }")
    L.append("}")
    return L


def 작은타일선형(epi, 이름=None):
    """32 × 32 칸을 블록 하나(256 스레드 = 가닥 4 × 64)가 — 행이 적어 64 × 64 블록이 GPU 를 다 채우지 못할 때. 스레드 하나가
    4 × 4 칸(행 ty·4 + r, 열 tx·4 + c). k 를 32 줄씩 세 판에 비동기복사로. 입력 판은 [k 32][행 32] 에 자리 m ^ s(k),
    s(k) = 4·((k/4) % 8). 가중치는 16 바이트씩 — 열수가 32 의 배수이고 시작이 16 바이트 정렬일 때만(호스트가 확인한다)."""
    I4, J4 = range(4), range(4)
    BK, AB, BB = 32, 32 * 32, 32 * 32
    B0 = 3 * AB
    이름 = 이름 or f"작은타일선형{epi}"
    L = [f"(* 32 × 32 칸을 블록 하나가 — 가닥 g 의 스레드 64 개가 k ≡ g (mod 4) 를 맡고, 스레드 하나가 4 × 4 칸 *)",
         f"(* 실행한도 {이름} 256 4 *)",
         f"[{머리(epi)} {이름}]는 {{",
         "    정수 tid = 블록안가로().",
         "    정수 가닥 = tid / 64.",
         "    정수 t64 = tid % 64.",
         "    정수 ty = t64 / 8.",
         "    정수 tx = t64 % 8.",
         "    정수 행0 = 블록가로() * 32.",
         "    정수 열0 = 블록세로() * 32.",
         "    짧은실수 참조 판 = 공유판24().",
         "    정수 a행 = 행0 + tid / 8.",
         "    a행 >= 행수이면 { a행 = 행수 - 1. }",
         "    정수 ak = (tid % 8) * 4.",
         "    정수 a저장 = ak * 32 + ((tid / 8) ^ ((tid % 8) * 4)).",
         "    정수 a원 = a행 * 깊이 + ak.",
         "    정수 열32 = 열수 * 32.",
         "    정수 b저장 = (tid / 8) * 32 + (tid % 8) * 4.",
         "    정수 b원 = (tid / 8) * 열수 + 열0 + (tid % 8) * 4.",
         f"    정수 타일수 = 깊이 / {BK}.",
         "    정수 올판 = 0."]

    def 올리기(판번호, ind):
        out = [f"{ind}올판 = {판번호}."]
        out += [f"{ind}비동기복사(판 에, 올판 * {AB} + a저장 + {32 * e} 를, 입력 에서, a원 + {e} 로)." for e in range(4)]
        out += [f"{ind}비동기복사16(판 에, {B0} + 올판 * {BB} + b저장 를, 가중치 에서, b원 로)."]
        return out

    def 다음(ind):
        return [f"{ind}a원 = a원 + {BK}.", f"{ind}b원 = b원 + 열32."]

    L += 올리기("0", "    ")
    L.append("    비동기묶기().")
    L.append("    타일수 > 1이면 {")
    L += 다음("        ")
    L += 올리기("1", "        ")
    L.append("    }")
    L.append("    비동기묶기().")
    L.append("    짧은실수 영 = 0 으로 짧은실수.")
    L += [f"    짧은실수 a{i}_{j} = 영." for i in I4 for j in J4]
    L += [f"    짧은실수 x{i} = 영." for i in I4]
    L += [f"    짧은실수 w{j} = 영." for j in J4]
    L += [f"    정수 ty4x{q} = (ty * 4) ^ {4 * q}." for q in range(8)]
    L += ["    정수 버퍼 = 0.", "    정수 앞판 = 2."]
    L.append("    반복 (정수 t는 0부터 타일수 전까지) {")
    L.append("        비동기기다리기(1).")
    L.append("        동기화().")
    L.append("        t + 2 < 타일수이면 {")
    L += 다음("            ")
    L += 올리기("앞판", "            ")
